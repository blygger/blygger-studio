// Regenerates words-en-us.ts from an ESDB (SCOWLv2) word list:
//   curl -o en_US-60.txt "https://app.aspell.net/create?max_size=60&spelling=US&max_variant=0&diacritic=strip&special=hacker&download=wordlist&encoding=utf-8&format=inline"
//   node --import tsx extensions/spellcheck/make-words.ts en_US-60.txt   (from the repository root)
// The list's header (its copyright notice and terms) is kept as NOTICE, as its licence asks.
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const [file] = process.argv.slice(2);
const raw = readFileSync(file, 'utf8');
const at = raw.indexOf('\n---\n');
if (at < 0) throw new Error('no "---" line after the header');
const notice = raw.slice(0, at).trim();
const words = raw.slice(at + 5).split('\n').map((w) => w.trim()).filter(Boolean);
const gz = gzipSync(words.join('\n'), { level: 9 }).toString('base64');
writeFileSync(
  'extensions/spellcheck/words-en-us.ts',
  `// Generated by make-words.ts: ${words.length} words, US English, ESDB size 60. Do not edit.\n` +
    `export const NOTICE = ${JSON.stringify(notice)};\n` +
    `export const WORDS = ${words.length};\n` +
    `/** The words, one per line, gzipped and base64-encoded. */\n` +
    `export const WORDS_GZ = ${JSON.stringify(gz)};\n`,
);
console.log(`${words.length} words, ${gz.length} base64 characters`);
