import { z } from 'zod';
import { sequenceOrder } from './sequence-order.ts';
import {
  zListItemsResponse,
  zGetItemResponse,
  zGetItemSummaryResponse,
  zVersion,
  zThumb,
  zInteraction,
  zBrowseStep,
  zGetSignalSummaryResponse,
  zHopper,
  zGetHopperResponse,
  zImportedItem,
  zReadingEntry,
  zGetReadingSummaryResponse,
  zSubscription,
  zMention,
  zGetMentionSourceResponse,
  zGetUpdateStateResponse,
  zAuthorization,
  zSettings,
  zSignal,
  zHopperMembership,
  zOutboundMention,
} from '../../sdk/dist/schemas.js';

const rank = z.number().int().nonnegative();
export const sourceSchemas = {
  items: zListItemsResponse.shape.items.element.transform(row => ({ ...row, isPlaceholder: row.placeholder !== null, orderKey: sequenceOrder([[row.updated, 'desc'], [row.id, 'desc']]) })),
  itemSummary: zGetItemSummaryResponse.extend({ key: z.literal('items') }),
  itemVersions: zVersion,
  itemHistory: zGetItemResponse.pick({
    id: true,
    media: true,
    publishedMedia: true,
    published: true,
  }),
  settings: zSettings.extend({ key: z.literal('settings') }),
  subscriptions: zSubscription,
  hoppers: zHopper,
  hopperStats: zGetHopperResponse.pick({ total: true, sourceCount: true })
    .extend({ id: zHopper.shape.id }),
  hopperEntries: z.object({ hopperId: zHopper.shape.id, rank, item: zImportedItem }),
  hopperMemberships: zHopperMembership.extend({ rank, item: zImportedItem.nullable() }),
  readingSummaries: zGetReadingSummaryResponse.extend({ view: z.string(), total: z.number().int().nonnegative() }),
  reading: zReadingEntry.extend({ view: z.string(), rank }),
  signals: zSignal,
  thumbs: zThumb.transform(row => ({ ...row, orderKey: sequenceOrder([[row.at, 'desc'], [row.subscriptionId ?? '', 'asc'], [row.remoteId, 'asc']]) })),
  interactions: zInteraction.transform(row => ({ ...row, orderKey: sequenceOrder([[row.at, 'desc'], [row.id, 'desc']]) })),
  browse: zBrowseStep,
  signalSummary: zGetSignalSummaryResponse.extend({ key: z.literal('signals') }),
  updates: zGetUpdateStateResponse.and(z.object({ key: z.literal('updates') })),
  authorizations: zAuthorization,
  inbound: zMention,
  outbound: zOutboundMention,
  mentionSources: zGetMentionSourceResponse.extend({ key: z.string() }),
};
